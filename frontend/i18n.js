const i18n = {
  lang: "uk",
  use(code) {
    this.lang = TRANSLATIONS[code] ? code : "uk";
    document.documentElement.lang = this.lang;
  },
  t(key, vars = {}) {
    const value = (TRANSLATIONS[this.lang] || {})[key] ?? key;
    return value.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
  },
  /** Проставляет переводы во всю разметку с data-i18n. */
  apply(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = this.t(node.dataset.i18n);
    });
  },
};
